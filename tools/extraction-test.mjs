import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
try {
  const page = await browser.newPage({ viewport: { width: 844, height: 390 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5191/?skip&still');
  await page.waitForFunction(() => window.__ready);
  const results = await page.evaluate(() => {
    const { round: R, camera, profile } = window.__game;
    const idle = { move: { x: 0, y: 0 }, turn: 0, firing: false };
    const checks = [];
    const check = (label, pass) => checks.push({ label, pass: !!pass });
    const reset = () => { R.reset(); R.start(); R.spawnTick = () => {}; R.pool.forEach(z => R.retire(z)); };
    reset();
    check('owned rifle starts a normal earning round', R.weapon.id === 'rifle' && !R.trial && profile.owns('rifle'));
    check('round wallet starts linked to profile', R.bank === profile.coins);
    const active = { ...idle, firing: true, move: { x: 1, y: 0 } };
    const rare = R.crates.find(c => c.rare);
    R.hero.root.position.set(rare.x, 0, rare.z);
    R.extraction.update(R, 2, active);
    check('demon chest stays locked in pickup range', rare.locked && !rare.opened && R.loot === 0);
    R.extraction.unlockRare();
    R.extraction.update(R, 0.001, active);
    check('unlocked demon chest opens immediately while moving and firing', rare.opened && R.loot === rare.value && !rare.lock.visible);
    R.extraction.update(R, 1, active);
    check('rare chest pays only once', R.loot === rare.value && R.opened === 1);
    reset();
    check('retry relocks demon chest', rare.locked && !rare.opened && rare.lock.visible);
    const c = R.crates[0]; R.hero.root.position.set(c.x, 0, c.z + 1.7);
    R.extraction.update(R, 2, idle);
    check('outside pickup range does not open crate', !c.opened && R.loot === 0);
    R.hero.root.position.set(c.x, 0, c.z + 1);
    R.extraction.update(R, 0, active);
    check('paused update does not collect crate', !c.opened && R.loot === 0);
    R.heroKick.set(2, 0, 0);
    R.extraction.update(R, 0.001, active);
    check('proximity instantly collects while moving, firing and knocked back', c.opened && R.loot === c.value && R.opened === 1);
    check('collected crate opens lid and hides marker without search progress', c.lid.rotation.x === -1.1 && !c.marker.visible && c.progress === 0);
    R.heroKick.set(0, 0, 0);
    R.extraction.update(R, 2, idle); check('no repeated payout', R.loot === c.value && R.opened === 1);
    R.elapsed = 89; R.hero.root.position.set(R.evac.x, 0, R.evac.z); R.extraction.update(R, 6, idle);
    check('no evacuation before signal', !R.evacOpen && R.state === 'play');
    R.elapsed = 90; R.extraction.update(R, 2, idle); check('signal opens evacuation', R.evacOpen && R.extracting === 2);
    R.hero.root.position.z = R.evac.z + 5; R.extraction.update(R, 2, idle); check('leaving circle pauses countdown', R.extracting === 2);
    R.hero.root.position.z = R.evac.z; const bank = R.bank; R.extraction.update(R, 3, idle);
    check('five seconds evacuates with all coins', R.state === 'win' && R.bank === bank + c.value && profile.coins === R.bank);
    R.finish(true); check('settlement cannot duplicate', R.bank === bank + c.value && profile.coins === R.bank);
    reset(); R.loot = 75; const b2 = R.bank; R.finish(false);
    check('death retains floor25percent', R.bank === b2 + 18 && profile.coins === R.bank);
    reset(); R.elapsed = 240; R.extraction.update(R, 1, idle);
    check('deadline closes car without automatic victory', R.missed && !R.evacOpen && R.state === 'play');
    R.update(0.1, idle, camera); check('missed car maximizes pressure', R.pressure === 100);
    reset(); R.update(1, idle, camera); const pressure = R.pressure;
    R.fire(camera); R.update(0.01, idle, camera); check('gunfire raises pressure', R.pressure > pressure + 0.1);
    const before = R.shots; R.update(0, { ...idle, firing: true }, camera); check('pause does not fire', R.shots === before);
    reset(); check('retry resets loot and crates, preserves profile wallet', R.loot === 0 && R.crates.every(c => !c.opened) && R.bank === b2 + 18 && profile.coins === R.bank);
    return checks;
  });
  for (const r of results) console.log(r.pass ? 'PASS' : 'FAIL', r.label);
  assert(results.every(r => r.pass));
  const settledCoins = await page.evaluate(() => window.__game.profile.coins);
  assert(settledCoins > 0, 'settlement earned coins');
  await page.goto('http://127.0.0.1:5191/');
  await page.waitForFunction(() => window.__ready);
  await page.getByRole('button', { name: '进入街道' }).waitFor();
  assert.deepEqual(await page.evaluate(() => ({ coins: window.__game.profile.coins, bank: window.__game.round.bank })), { coins: settledCoins, bank: settledCoins }, 'profile and round wallet preserve settlements on reload into the shop');
  assert.equal(await page.locator('.wallet b').innerText(), String(settledCoins));
  console.log('PASS settlement wallet persists into the shop after reload');
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
