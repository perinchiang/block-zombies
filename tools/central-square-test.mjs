import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
try {
  const page = await browser.newPage({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5191/?still'); await page.waitForFunction(() => window.__ready);
  const checks = await page.evaluate(async () => {
    const { round: r, camera, profile } = window.__game;
    const { ENTRANCES, encounterPhase } = await import('/src/game/spawn-director.js');
    const { nextWaypoint, isWalkable } = await import('/src/world/navigation.js');
    const THREE = await import('/node_modules/three/build/three.module.js');
    const out = [], check = (name, ok) => out.push({ name, ok: !!ok });
    const reset = () => { r.reset('rifle'); r.start(); r.pool.forEach(z => r.retire(z)); };
    reset();
    r.hero.root.position.set(0, 0, 5); r.yaw = 0;
    r.director.update(1.1, r);
    let z = r.pool.find(z => z.active);
    check('first spawn at fixed west gate independent of facing', z && z.root.position.x === ENTRANCES[0].x && z.root.position.z === ENTRANCES[0].z && z.rise === 1);
    reset(); r.elapsed = 65; r.director.update(1.1, r); z = r.pool.find(z => z.active);
    check('later phase uses east gate', z && z.root.position.x === ENTRANCES[1].x);
    check('quiet interval stops new gate groups', encounterPhase(50).quiet && encounterPhase(116).quiet);
    reset(); r.elapsed = 48; r.hero.root.position.set(-16, 0, 6); r.director.graveTimer = 0;
    r.director.update(0.01, r);
    check('grave first shows warning without spawning', r.director.pending && r.alive === 0 && r.director.warning.visible);
    const pending = { ...r.director.pending };
    r.state = 'paused'; r.director.update(10, r);
    check('pause freezes grave warning', r.director.pending.remaining === pending.remaining);
    r.state = 'play'; r.director.update(2.3, r);
    z = r.pool.find(z => z.active);
    check('grave emerges at warned location after countdown', z && z.root.position.x === pending.x && z.root.position.z === pending.z && z.rise === 0);
    reset(); r.elapsed = 48; r.hero.root.position.set(-16, 0, 6); r.director.graveTimer = 0; r.director.update(0.01, r);
    r.hero.root.position.set(r.director.pending.x, 0, r.director.pending.z); r.director.update(2.3, r);
    check('warning does not spawn enemy under player', r.alive === 0);
    reset(); r.hero.root.position.set(0, 0, -9); z = r.spawn(0, -11, false, false); z.hp = 20;
    r.damage(z, new THREE.Vector3(0, 0, -1), 1, 1, { weaponId: 'rifle', control: true });
    const oldZ = z.root.position.z; r.updateZombies(0.05, true);
    check('rifle actually stops pursuit and pushes away', z.stunT > 0 && z.root.position.z < oldZ && z.biteT === 0);
    reset(); r.hero.root.position.set(0, 0, 5); z = r.spawn(-16, -9, false, false);
    let penetrated = false;
    for (let i = 0; i < 900; i++) { r.updateZombies(0.02, true); if (!isWalkable(z.root.position.x, z.root.position.z, 0.29, r.colliders)) penetrated = true; }
    check('zombie navigates building to reach central square', z.root.position.distanceTo(r.hero.root.position) < 4 && !penetrated);
    reset(); r.hero.root.position.set(0, 0, 5); z = r.spawn(-13.3, -9, false, false);
    z.vel.set(2, 0, 0);
    for (let i = 0; i < 900; i++) r.updateZombies(0.02, true);
    check('wall-pinned zombie recovers pursuit after knockback', z.root.position.distanceTo(r.hero.root.position) < 4 && isWalkable(z.root.position.x, z.root.position.z, 0.38, r.colliders));
    reset(); r.hp = 3; r.hero.root.position.copy(r.extraction.recovery.position); r.extraction.update(r, 0.02);
    r.extraction.update(r, 0.02); check('recovery restores exactly one heart once', r.hp === 4 && r.extraction.recovered);
    reset(); r.elapsed = 90; r.hero.root.position.set(r.evac.x, 0, r.evac.z); r.extraction.update(r, 2);
    check('central car arrives and boarding starts beside door', r.evac.z === 0 && r.extraction.vehicle.visible && r.extracting === 2 && r.vehiclePresent);
    r.hero.root.position.set(0, 0, 5); r.extraction.update(r, 1); check('leaving boarding preserves progress', r.extracting === 2);
    r.hero.root.position.set(r.evac.x, 0, r.evac.z); r.extraction.update(r, 3); check('central boarding finishes round', r.state === 'win');
    // Durable upgrade changes the next round; current config cannot be mutated midflight.
    profile.earn(1000); profile.upgrade('rifle'); r.reset('rifle');
    const damage = r.weapon.damageMultiplier, level = r.weapon.level;
    r.start(); r.pool.forEach(z => r.retire(z));
    const victim = r.spawn(0, -12, false, false); victim.hp = 20; victim.pose(0); r.scene.updateMatrixWorld(true);
    const shot = { pierce: false, blast: false, hit: false, exploded: false };
    r.ballistics.fire(new THREE.Vector3(0, 0.95, -10), new THREE.Vector3(0, 0, -1), r.weapon, shot);
    profile.upgrade('rifle');
    check('round locks equipped upgrade level', r.weapon.damageMultiplier === damage && r.weapon.level === level);
    r.ballistics.update(0.1); check('upgraded projectile applies captured damage multiplier', victim.hp === 20 - damage);
    r.reset('rifle'); check('next round receives purchased upgrade', r.weapon.level > level && r.ammo === r.weapon.mag);
    r.reset('shotgun', { trial: true }); check('trial remains level one', r.weapon.level === 1 && r.ammo === 6);
    return out;
  });
  for (const c of checks) console.log(c.ok ? 'PASS' : 'FAIL', c.name);
  assert(checks.every(c => c.ok)); assert.deepEqual(errors, []);
} finally { await browser.close(); }
